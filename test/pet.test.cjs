const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { PetState, normalizeEvent } = require('../src/state.cjs');
const { createBridge } = require('../src/bridge.cjs');
test('validates and bounds event data', () => {
  assert.throws(() => normalizeEvent({ state: 'injected' }));
  assert.equal(normalizeEvent({ state: 'done', title: 'x'.repeat(500) }).title.length, 120);
});
test('deduplicates and resumes another active session after completion', () => {
  const state = new PetState();
  state.accept({ state: 'thinking', sessionId: 'a' });
  state.accept({ state: 'thinking', sessionId: 'b' });
  state.accept({ state: 'done', sessionId: 'a', eventId: 'a:2' });
  assert.equal(state.accept({ state: 'done', sessionId: 'a', eventId: 'a:2' }), null);
  assert.equal(state.idle().sessionId, 'b');
  state.accept({ state: 'sleeping', sessionId: 'b' });
  assert.equal(state.idle().state, 'sleeping');
});
test('permission requests stay visible until all are resolved, even across other chats', () => {
  const state = new PetState();
  state.accept({ state: 'thinking', sessionId: 'a' });
  state.accept({ state: 'permission', sessionId: 'a', requestId: 'p1', eventId: 'p1:open' });
  assert.equal(state.accept({ state: 'permission', sessionId: 'a', requestId: 'p1', eventId: 'p1:open' }), null);
  state.accept({ state: 'permission', sessionId: 'a', requestId: 'p2' });
  state.accept({ state: 'thinking', sessionId: 'b' });
  state.accept({ state: 'done', sessionId: 'b' });
  assert.equal(state.current.state, 'permission');
  assert.equal(state.idle().state, 'permission');
  state.accept({ state: 'permission-resolved', sessionId: 'a', requestId: 'p1' });
  assert.equal(state.current.requestId, 'p2');
  state.accept({ state: 'permission-resolved', sessionId: 'a', requestId: 'p2' });
  assert.equal(state.current.state, 'thinking');
  state.accept({ state: 'permission', sessionId: 'a', requestId: 'p3' });
  state.accept({ state: 'sleeping', sessionId: 'a' });
  assert.equal(state.permissions.size, 0);
  assert.equal(state.current.state, 'sleeping');
});
test('plugin maps actual lifecycle events without content or child-session leaks', async () => {
  const { notificationFor } = await import('../dsh-plugin.mjs');
  const session = { id: 'chat', header: {} };
  const event = kind => ({ type: 'turn/end', seq: 4, data: { reason: { kind }, content: 'SECRET' } });
  assert.equal(notificationFor(session, { type: 'turn/start', seq: 3 }).state, 'thinking');
  assert.equal(notificationFor(session, event('completed')).state, 'done');
  assert.equal(notificationFor(session, event('max-tokens')).state, 'hungry');
  assert.equal(notificationFor(session, event('error')).state, 'error');
  for (const kind of ['aborted', 'blocked', 'interrupted', 'forked']) assert.equal(notificationFor(session, event(kind)).state, 'sleeping');
  assert.equal(notificationFor({ ...session, header: { origin: 'subagent' } }, event('completed')), null);
  assert.equal(notificationFor({ ...session, header: { delegationDepth: 1 } }, event('completed')), null);
  assert.equal(notificationFor(session, { type: 'message/updated' }), null);
  assert.ok(!JSON.stringify(notificationFor(session, event('completed'))).includes('SECRET'));
});
test('approval mapping is permission-specific and does not leak tool details', async () => {
  const { notificationFor } = await import('../dsh-plugin.mjs');
  const session = { id: 'chat', header: {} };
  const asked = { type: 'approval/asked', seq: 10, data: { id: 'req', reason: 'PRIVATE command', toolName: 'bash' } };
  const notice = notificationFor(session, asked);
  assert.equal(notice.state, 'permission');
  assert.equal(notice.requestId, 'req');
  assert.ok(!JSON.stringify(notice).includes('PRIVATE'));
  assert.equal(notificationFor(session, { type: 'approval/decided', seq: 11, data: { id: 'req', outcome: 'rejected' } }).state, 'permission-resolved');
  assert.equal(notificationFor(session, { type: 'user-questions/request', data: {} }), null);
  assert.equal(notificationFor({ ...session, header: { origin: 'subagent' } }, asked), null);
  assert.equal(notificationFor(session, { ...asked, data: {} }), null);
});
test('permission alerts debounce immediate decisions and clean up on decision, end, disposal', async t => {
  const { createPermissionDispatcher } = await import('../dsh-plugin.mjs');
  t.mock.timers.enable({ apis: ['setTimeout'] });
  const sent = [];
  const dispatcher = createPermissionDispatcher(event => sent.push(event));
  const session = { id: 'chat', header: {} };
  let seq = 0;
  const emit = (type, id, outcome) => dispatcher.accept(session, { type, seq: ++seq, data: { id, outcome, reason: { kind: 'completed' } } });
  emit('approval/asked', 'instant');
  emit('approval/decided', 'instant', 'rejected');
  t.mock.timers.tick(500);
  assert.equal(sent.length, 0);
  emit('approval/asked', 'p1'); emit('approval/asked', 'p2');
  t.mock.timers.tick(500);
  assert.deepEqual(sent.map(e => e.state), ['permission', 'permission']);
  emit('approval/decided', 'p1', 'allowed-once');
  assert.equal(sent.at(-1).requestId, 'p1');
  assert.equal(sent.at(-1).state, 'permission-resolved');
  emit('turn/end');
  assert.deepEqual(sent.slice(-2).map(e => e.state), ['permission-resolved', 'done']);
  emit('approval/asked', 'never-alert');
  emit('turn/end');
  const length = sent.length;
  t.mock.timers.tick(500);
  assert.equal(sent.length, length);
  emit('approval/asked', 'disposed');
  dispatcher.sessionDisposed(session);
  t.mock.timers.tick(500);
  assert.equal(sent.at(-1).state, 'sleeping');
  emit('approval/asked', 'stop');
  dispatcher.dispose();
  const stopped = sent.length;
  t.mock.timers.tick(500);
  assert.equal(sent.length, stopped);
});
test('bridge requires auth, rejects browser callers and invalid payloads', async t => {
  const state = new PetState(); let count = 0;
  const server = createBridge({ token: 'test-token', port: 0, onEvent: event => { state.accept(event); count++; } });
  t.after(() => { server.closeAllConnections(); server.close(); });
  await once(server, 'listening');
  const url = `http://127.0.0.1:${server.address().port}/event`;
  const post = (body, headers = {}) => fetch(url, { method: 'POST', headers, body: JSON.stringify(body) });
  assert.equal((await post({ state: 'done' })).status, 401);
  const auth = { authorization: 'Bearer test-token' };
  assert.equal((await post({ state: 'done' }, { ...auth, origin: 'https://example.com' })).status, 403);
  assert.equal((await post({ state: 'bogus' }, auth)).status, 400);
  assert.equal((await post({ state: 'done', title: 'Reply ready' }, auth)).status, 200);
  assert.equal(count, 1);
  assert.equal(state.current.state, 'done');
  assert.equal((await post({ state: 'done', title: 'x'.repeat(9000) }, auth)).status, 413);
});
